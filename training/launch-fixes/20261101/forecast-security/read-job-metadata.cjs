/* Read-only aggregate notification metadata. No notification body, user, email or tenant is returned. */
const fs = require('node:fs');
const path = require('node:path');
const { loadEnvConfig } = require('@next/env');
const { createClient } = require('@supabase/supabase-js');
loadEnvConfig(process.cwd(), false, { info() {}, error() {} });
async function main() {
  const client = createClient(process.env.NEXT_PUBLIC_SUPABASE_URL, process.env.SUPABASE_SERVICE_ROLE_KEY, { auth: { persistSession: false, autoRefreshToken: false } });
  const today = new Date().toISOString().slice(0, 10);
  const start = `${today}T00:00:00Z`;
  const report = { at: new Date().toISOString(), scope: 'Head-only aggregate counts, no identities, notification content or credentials. No cron or email invoked.', utcDay: today, counts: {}, limitation: 'Rows may be generated by dashboard visits as well as cron. Counts do not establish successful scheduled execution or email delivery.' };
  for (const [label, query] of [
    ['trialReminderRowsToday', client.from('app_notifications').select('id', { head: true, count: 'exact' }).eq('metadata->>kind', 'trial_reminder').gte('created_at', start)],
    ['trialReminderRowsInScheduledWindow06to07UTC', client.from('app_notifications').select('id', { head: true, count: 'exact' }).eq('metadata->>kind', 'trial_reminder').gte('created_at', `${today}T06:00:00Z`).lt('created_at', `${today}T07:00:00Z`)],
    ['candidateSubscriptionRows', client.from('organization_subscriptions').select('id', { head: true, count: 'exact' }).in('status', ['trialing', 'past_due', 'canceled', 'unpaid'])],
  ]) {
    const result = await query;
    report.counts[label] = result.error ? { available: false, errorCode: result.error.code } : { available: true, count: result.count };
  }
  fs.writeFileSync(path.join(__dirname, 'job-metadata.json'), JSON.stringify(report, null, 2) + '\n');
  console.log(JSON.stringify(report));
}
main().catch(() => { console.error('Read-only job metadata unavailable; no private details logged. No mutation attempted.'); process.exitCode = 1; });
