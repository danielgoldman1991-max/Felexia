-- Public PRO uses the existing durable `premium` plan code.
-- Additive write guards only: no plan, subscription, business row, number,
-- currency, SELECT policy or existing permission is rewritten.
-- Apply manually after 103. This file does not enable PRO for any company.
begin;

create or replace function app_private.assert_pro_write_access(p_organization_id uuid, p_require_pro boolean default true)
returns void language plpgsql volatile security definer set search_path=public,app_private as $$
declare plan text;
begin
  perform app_private.assert_essential_write_access(p_organization_id);
  if auth.uid() is null then return; end if; -- trusted maintenance, checked by 099
  if p_require_pro then
    select plan_code into plan from public.organization_subscriptions
      where organization_id=p_organization_id order by created_at desc limit 1 for share;
    if plan is null or plan not in ('premium','pro') then
      raise exception 'PRO_PLAN_REQUIRED' using errcode='42501';
    end if;
  end if;
end $$;
revoke all on function app_private.assert_pro_write_access(uuid,boolean) from public,anon,authenticated,service_role;

create or replace function app_private.guard_pro_erp_write()
returns trigger language plpgsql security definer set search_path=public,app_private as $$
declare
  org uuid := case when TG_OP='DELETE' then old.organization_id else new.organization_id end;
  automatic_stock boolean := TG_TABLE_NAME in ('stock_moves','stock_levels','warehouses') and pg_trigger_depth()>1;
begin
  -- Nested stock updates generated by an admitted business operation retain
  -- the original operation's access. Direct stock writes always require PRO.
  -- Subscription expiry and tenant membership still apply to both paths.
  perform app_private.assert_pro_write_access(org,not automatic_stock);
  if auth.uid() is not null then
    if not automatic_stock and (app_private.is_read_only_org_member(org) or app_private.is_operator_org_member(org)) then
      raise exception 'PRO_WRITE_ROLE_REQUIRED' using errcode='42501';
    end if;
    if TG_TABLE_NAME like 'hr\_%' escape '\' and not public.hr_can_manage(org) then
      raise exception 'HR_MANAGEMENT_REQUIRED' using errcode='42501';
    end if;
  end if;
  if TG_OP='UPDATE' and old.organization_id is distinct from new.organization_id then
    raise exception 'ORGANIZATION_IMMUTABLE' using errcode='42501';
  end if;
  if TG_OP='UPDATE' and (to_jsonb(old)->>'id') is distinct from (to_jsonb(new)->>'id') then
    raise exception 'IMMUTABLE_RECORD_KEY' using errcode='42501';
  end if;
  if TG_OP='DELETE' then return old; end if;
  return new;
end $$;
revoke all on function app_private.guard_pro_erp_write() from public,anon,authenticated,service_role;

do $$
declare target record;
begin
  if to_regprocedure('app_private.assert_essential_write_access(uuid)') is null
    or to_regprocedure('public.hr_can_manage(uuid)') is null then
    raise exception 'PRO_PREREQUISITE_MIGRATIONS_REQUIRED';
  end if;
  for target in
    select c.relname,c.relrowsecurity from pg_class c
    join pg_namespace n on n.oid=c.relnamespace
    join pg_attribute a on a.attrelid=c.oid and a.attname='organization_id' and not a.attisdropped
    where n.nspname='public' and c.relkind in ('r','p') and (
      c.relname like 'hr\_%' escape '\' or c.relname=any(array[
        'stock_moves','stock_levels','warehouses','inventory_adjustments','inventory_adjustment_lines',
        'sales_documents','sales_document_lines','sales_quotes','sales_quote_lines','sales_orders','sales_order_lines','delivery_notes','delivery_note_lines',
        'purchase_documents','purchase_document_lines','purchase_orders','purchase_order_lines','goods_receipts','goods_receipt_lines',
        'documents','bank_statement_imports','bank_statement_lines','bank_reconciliations',
        'treasury_forecast_items','cashflow_forecasts','vat_declarations','tax_export_batches'
      ])
    )
  loop
    if not target.relrowsecurity then raise exception 'RLS_DISABLED_REQUIRES_REVIEW: %',target.relname; end if;
    execute format('drop trigger if exists aa_pro_erp_write_guard on public.%I',target.relname);
    execute format('create trigger aa_pro_erp_write_guard before insert or update or delete on public.%I for each row execute function app_private.guard_pro_erp_write()',target.relname);
  end loop;
end $$;

-- Storage uploads are independent requests. Deny unpaid/Essentiel writes
-- before they can leave an orphan file. Existing download policies remain.
create or replace function app_private.can_write_pro_storage(p_bucket text,p_name text)
returns boolean language plpgsql volatile security definer set search_path=public,app_private as $$
declare org_text text; org uuid;
begin
  if p_bucket not in ('organization-documents','hr-documents','tax-exports') then return true; end if;
  org_text := case when split_part(p_name,'/',1)='organizations' then split_part(p_name,'/',2) else split_part(p_name,'/',1) end;
  if org_text !~* '^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$' then return false; end if;
  org := org_text::uuid;
  perform app_private.assert_pro_write_access(org,true);
  if auth.uid() is null or app_private.is_read_only_org_member(org) or app_private.is_operator_org_member(org) then return false; end if;
  if p_bucket='hr-documents' and not public.hr_can_manage(org) then return false; end if;
  return true;
exception when insufficient_privilege then return false;
end $$;
revoke all on function app_private.can_write_pro_storage(text,text) from public,anon,authenticated,service_role;
grant execute on function app_private.can_write_pro_storage(text,text) to authenticated;

do $$ begin
  if to_regclass('storage.objects') is not null then
    execute 'drop policy if exists pro_storage_insert_guard_104 on storage.objects';
    execute 'drop policy if exists pro_storage_update_guard_104 on storage.objects';
    execute 'drop policy if exists pro_storage_delete_guard_104 on storage.objects';
    execute 'create policy pro_storage_insert_guard_104 on storage.objects as restrictive for insert to authenticated with check(app_private.can_write_pro_storage(bucket_id,name))';
    execute 'create policy pro_storage_update_guard_104 on storage.objects as restrictive for update to authenticated using(app_private.can_write_pro_storage(bucket_id,name)) with check(app_private.can_write_pro_storage(bucket_id,name))';
    execute 'create policy pro_storage_delete_guard_104 on storage.objects as restrictive for delete to authenticated using(app_private.can_write_pro_storage(bucket_id,name))';
  end if;
end $$;

create or replace function public.erp_get_capabilities(p_organization_id uuid)
returns jsonb language plpgsql stable security definer set search_path=public,app_private as $$
begin
  if auth.uid() is null or not app_private.is_org_member(p_organization_id) then
    raise exception 'SUBSCRIPTION_MEMBERSHIP_REQUIRED' using errcode='42501';
  end if;
  return jsonb_build_object('workflow_version',104,'pro_write_guards',true);
end $$;
revoke all on function public.erp_get_capabilities(uuid) from public,anon,authenticated,service_role;
grant execute on function public.erp_get_capabilities(uuid) to authenticated;

notify pgrst,'reload schema';
commit;

select exists(select 1 from pg_proc p join pg_namespace n on n.oid=p.pronamespace where n.nspname='public' and p.proname='erp_get_capabilities')
  and exists(select 1 from pg_trigger where tgname='aa_pro_erp_write_guard' and tgrelid='public.hr_employees'::regclass)
  and exists(select 1 from pg_trigger where tgname='aa_pro_erp_write_guard' and tgrelid='public.stock_moves'::regclass) as pro_104_actif;
